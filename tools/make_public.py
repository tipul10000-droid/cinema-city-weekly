"""Build the public app (docs/app/) from the family app (docs/index.html).

Both apps are the same page; index.html tells them apart by its path. The copy only gets a <base> so the
shared files (data.json, posters, icons) resolve to docs/, its own manifest (so it installs as a separate
home-screen app) and its own service worker (so its push subscription is separate from the family's).
Runs in CI on every change to docs/index.html, docs/sw.js or docs/manifest.json; run it locally too:
    python3 tools/make_public.py
"""
import json
import pathlib

DOCS = pathlib.Path(__file__).resolve().parent.parent / "docs"
APP = DOCS / "app"


def main():
    APP.mkdir(exist_ok=True)
    page = (DOCS / "index.html").read_text(encoding="utf-8")
    for old, new in [
        ('<meta charset="utf-8">', '<meta charset="utf-8">\n<base href="../">'),
        ('<link rel="manifest" href="manifest.json">', '<link rel="manifest" href="app/manifest.json">'),
    ]:
        assert page.count(old) == 1, old
        page = page.replace(old, new)
    banner = "<!-- generated by tools/make_public.py from docs/index.html; edit that file, not this one -->\n"
    (APP / "index.html").write_text(banner + page, encoding="utf-8")
    (APP / "sw.js").write_text((DOCS / "sw.js").read_text(encoding="utf-8"), encoding="utf-8")
    manifest = json.loads((DOCS / "manifest.json").read_text(encoding="utf-8"))
    manifest.update(id="./", start_url="./", scope="./")
    for icon in manifest.get("icons", []):
        icon["src"] = "../" + icon["src"]
    (APP / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
